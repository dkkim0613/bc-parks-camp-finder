import type { Metadata } from "next";
import { headers } from "next/headers";
import "./globals.css";

export async function generateMetadata(): Promise<Metadata> {
  const requestHeaders = await headers();
  const host =
    requestHeaders.get("x-forwarded-host") ?? requestHeaders.get("host") ?? "localhost:3000";
  const protocol =
    requestHeaders.get("x-forwarded-proto") ?? (host.includes("localhost") ? "http" : "https");
  const origin = `${protocol}://${host}`;
  return {
    metadataBase: new URL(origin),
    title: "BC Parks Camp Finder",
    description: "Flexible-date BC Parks camping and cabin availability dashboard.",
    openGraph: {
      title: "BC Parks Camp Finder",
      description:
        "Find realistic camping and cabin openings near home, then jump to BC Parks with a ready booking summary.",
      url: origin,
      siteName: "BC Parks Camp Finder",
      type: "website",
    },
  };
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body>{children}</body>
    </html>
  );
}
